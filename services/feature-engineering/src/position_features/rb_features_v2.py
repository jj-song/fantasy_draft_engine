    def engineer_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Generate RB-specific features from player data.
        
        Args:
            df: DataFrame containing RB player data
            
        Returns:
            DataFrame with RB-specific features added
        """
        if not self.validate_data(df):
            return df.copy()
        
        # Filter to RB data only
        df_rb = df[df['position'] == 'RB'].copy()
        
        if df_rb.empty:
            return df_rb
        
        self.logger.info(f"Engineering features for {len(df_rb)} RB records")
        
        try:
            # Calculate basic efficiency metrics
            df_rb = self._calculate_efficiency_metrics(df_rb)
            
            # Calculate per-game averages
            df_rb = self._calculate_per_game_metrics(df_rb)
            
            # Calculate usage and opportunity metrics
            df_rb = self._calculate_usage_metrics(df_rb)
            
            # Calculate advanced metrics
            df_rb = self._calculate_advanced_metrics(df_rb)
            
            # Calculate role classification features
            df_rb = self._calculate_role_classification(df_rb)
            
            self.logger.info("RB feature engineering completed successfully")
            return df_rb
            
        except Exception as e:
            self.logger.error(f"Error in RB feature engineering: {str(e)}")
            raise
    
    def _calculate_efficiency_metrics(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculate RB efficiency metrics using centralized column mapping.
        
        Args:
            df: DataFrame containing RB player data
            
        Returns:
            DataFrame with RB efficiency metrics added
        """
        df = df.copy()
        
        # Get standardized column mappings
        rushing_cols = self.column_mapper.get_column_mapping(df, ['rushing'])
        receiving_cols = self.column_mapper.get_column_mapping(df, ['receiving'])
        
        # Yards per carry
        carries_col = rushing_cols.get('rushing_attempts')
        rushing_yards_col = rushing_cols.get('rushing_yards')
        
        if carries_col and rushing_yards_col:
            df['yards_per_carry'] = np.where(
                df[carries_col] > 0,
                df[rushing_yards_col] / df[carries_col],
                0.0
            )
        else:
            df['yards_per_carry'] = 0.0
        
        # Yards per reception
        receptions_col = receiving_cols.get('receptions')
        receiving_yards_col = receiving_cols.get('receiving_yards')
        
        if receptions_col and receiving_yards_col:
            df['yards_per_reception'] = np.where(
                df[receptions_col] > 0,
                df[receiving_yards_col] / df[receptions_col],
                0.0
            )
        else:
            df['yards_per_reception'] = 0.0
        
        # Calculate total touches and yards
        touches = 0
        total_yards = 0
        
        if carries_col and carries_col in df.columns:
            touches += df[carries_col]
        if receptions_col and receptions_col in df.columns:
            touches += df[receptions_col]
            
        if rushing_yards_col and rushing_yards_col in df.columns:
            total_yards += df[rushing_yards_col]
        if receiving_yards_col and receiving_yards_col in df.columns:
            total_yards += df[receiving_yards_col]
        
        # Yards per touch
        df['yards_per_touch'] = np.where(touches > 0, total_yards / touches, 0.0)
        
        # Touchdowns per touch
        total_tds = 0
        rushing_tds_col = rushing_cols.get('rushing_touchdowns')
        receiving_tds_col = receiving_cols.get('receiving_touchdowns')
        
        if rushing_tds_col and rushing_tds_col in df.columns:
            total_tds += df[rushing_tds_col]
        if receiving_tds_col and receiving_tds_col in df.columns:
            total_tds += df[receiving_tds_col]
            
        df['touchdowns_per_touch'] = np.where(touches > 0, total_tds / touches, 0.0)
        
        # Catch rate
        targets_col = receiving_cols.get('targets')
        if targets_col and receptions_col and targets_col in df.columns and receptions_col in df.columns:
            df['catch_rate'] = np.where(
                df[targets_col] > 0,
                df[receptions_col] / df[targets_col],
                0.0
            )
        else:
            df['catch_rate'] = 0.0
        
        return df
    
    def _calculate_per_game_metrics(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculate RB per-game metrics using centralized utilities.
        
        Args:
            df: DataFrame containing RB player data
            
        Returns:
            DataFrame with RB per-game metrics added
        """
        df = df.copy()
        
        # Get games played column
        general_cols = self.column_mapper.get_column_mapping(df, ['general'])
        games_col = general_cols.get('games')
        if not games_col:
            self.logger.warning("No games column found for per-game calculations")
            # Set all per-game metrics to 0
            per_game_metrics = [
                'rushing_yards_per_game', 'rushing_tds_per_game', 'carries_per_game',
                'receiving_yards_per_game', 'receiving_tds_per_game', 'receptions_per_game',
                'targets_per_game', 'touches_per_game', 'total_yards_per_game', 'total_tds_per_game'
            ]
            for metric in per_game_metrics:
                df[metric] = 0.0
            return df
        
        # Get column mappings
        rushing_cols = self.column_mapper.get_column_mapping(df, ['rushing'])
        receiving_cols = self.column_mapper.get_column_mapping(df, ['receiving'])
        
        # Avoid division by zero
        games_played = df[games_col].replace(0, 1)
        
        # Rushing per-game stats
        rushing_stats = {
            'rushing_yards_per_game': rushing_cols.get('rushing_yards'),
            'rushing_tds_per_game': rushing_cols.get('rushing_touchdowns'),
            'carries_per_game': rushing_cols.get('rushing_attempts')
        }
        
        for stat_name, col_name in rushing_stats.items():
            if col_name and col_name in df.columns:
                df[stat_name] = df[col_name] / games_played
            else:
                df[stat_name] = 0.0
        
        # Receiving per-game stats
        receiving_stats = {
            'receiving_yards_per_game': receiving_cols.get('receiving_yards'),
            'receiving_tds_per_game': receiving_cols.get('receiving_touchdowns'),
            'receptions_per_game': receiving_cols.get('receptions'),
            'targets_per_game': receiving_cols.get('targets')
        }
        
        for stat_name, col_name in receiving_stats.items():
            if col_name and col_name in df.columns:
                df[stat_name] = df[col_name] / games_played
            else:
                df[stat_name] = 0.0
        
        # Combined per-game stats
        df['touches_per_game'] = df['carries_per_game'] + df['receptions_per_game']
        df['total_yards_per_game'] = df['rushing_yards_per_game'] + df['receiving_yards_per_game']
        df['total_tds_per_game'] = df['rushing_tds_per_game'] + df['receiving_tds_per_game']
        
        return df
    
