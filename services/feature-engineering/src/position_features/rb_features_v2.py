    def _calculate_role_classification(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculate RB role classification scores based on usage patterns.
        
        Args:
            df: DataFrame containing RB player data
            
        Returns:
            DataFrame with role classification features added
        """
        df = df.copy()
        
        # Workhorse score (based on carry volume and consistency)
        df['workhorse_score'] = np.where(
            df['carries_per_game'] >= 15,
            df['carries_per_game'] / 20.0,  # Scale to 0-1
            0.0
        )
        
        # Committee back score (inverse of workhorse)
        df['committee_back_score'] = np.where(
            df['carries_per_game'] < 12,
            1.0 - (df['carries_per_game'] / 12.0),
            0.0
        )
        
        # Pass-catching back score (based on targets and receptions)
        df['pass_catching_back_score'] = np.where(
            df['targets_per_game'] >= 3,
            df['targets_per_game'] / 8.0,  # Scale to 0-1
            0.0
        )
        
        # Goal line back score (would be based on goal line carries if available)
        df['goal_line_back_score'] = 0.0
        
        # Versatility score (combination of rushing and receiving)
        rush_component = np.minimum(df['carries_per_game'] / 15.0, 1.0)
        receiving_component = np.minimum(df['targets_per_game'] / 5.0, 1.0)
        df['rb_versatility_score'] = (rush_component + receiving_component) / 2.0
        
        # Consistency metrics (would need game-by-game data)
        df['rb_efficiency_consistency'] = 0.0
        df['weekly_touch_volatility'] = 0.0
        df['boom_game_rate'] = 0.0
        df['bust_game_rate'] = 0.0
        
        return df


